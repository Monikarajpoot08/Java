//30. Write a Java program using the Math class to perform mathematical operations such as power, square
//root, maximum, minimum and rounding.
class MathOperations {
    public static void main(String[] args) {
        System.out.println("Power: " + Math.pow(2, 3));
        System.out.println("Square root: " + Math.sqrt(25));
        System.out.println("Maximum: " + Math.max(10, 20));
        System.out.println("Minimum: " + Math.min(10, 20));
        System.out.println("Rounding: " + Math.round(5.7));
    }
}