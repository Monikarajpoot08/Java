//2. Write a Java program to demonstrate the use of variables and different data types in Java.
public class DataTypesDemo {
        public static void main(String[] args) {
        int age = 20;
        float height = 5.6f;
        double salary = 25000.50;
        char grade = 'A';
        boolean isStudent = true;
        byte marks = 90;
        short year = 2026;
        long population = 1400000000L;
        String name = "Anjali";
        System.out.println("Name: " + name + "| Age: " + age + "| Height: " + height);
        System.out.println("Salary: " + salary + "| Grade: " + grade + "| Is Student: " + isStudent);
        System.out.println("Marks: " + marks + "| Year: " + year + "| Population: " + population);
    }
} 
